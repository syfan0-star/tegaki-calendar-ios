    private func key(_ ymd: String) -> DayKey {
        let parts = ymd.split(separator: "-").map { Int($0)! }
        return DayKey(year: parts[0], month: parts[1], day: parts[2])
    }

    private func yearOf(_ y: Int) -> [String] {
        JapaneseHolidays.holidays(ofYear: y).map { "\($0.day) \($0.name)" }
    }

    func testHolidaysOfEachVectorYearMatchExactly() {
        for (year, expected) in Self.vectors.sorted(by: { $0.key < $1.key }) {
            XCTAssertEqual(yearOf(year), expected.map { "\($0.0) \($0.1)" }, "year \(year)")
            // Same answer through the range API and per-day lookup.
            let range = JapaneseHolidays.holidays(from: DayKey(year: year, month: 1, day: 1), through: DayKey(year: year, month: 12, day: 31))
            XCTAssertEqual(range.map { "\($0.day) \($0.name)" }, yearOf(year), "range API, year \(year)")
            for (date, name) in expected {
                XCTAssertEqual(JapaneseHolidays.name(of: key(date)), name, date)
            }
        }
    }

    func testDateSetsMatchTheOfficialCSVForEveryYear2000To2027() {
        for (year, mmdd) in Self.officialDateSets.sorted(by: { $0.key < $1.key }) {
            let expected = mmdd.split(separator: " ").map { "\(year)-\($0.prefix(2))-\($0.suffix(2))" }
            XCTAssertEqual(JapaneseHolidays.holidays(ofYear: year).map { $0.day.description }, expected, "year \(year)")
        }
    }

    func testEquinoxHolidaysMatchTheNAOJTable2020To2050() {
        for (year, days) in Self.naojEquinoxes.sorted(by: { $0.key < $1.key }) {
            XCTAssertEqual(JapaneseHolidays.name(of: DayKey(year: year, month: 3, day: days.0)), "春分の日", "\(year) 春分")
            XCTAssertEqual(JapaneseHolidays.name(of: DayKey(year: year, month: 9, day: days.1)), "秋分の日", "\(year) 秋分")
        }
    }

    func testRuleChangesBefore2007AndOtherEdgeCases() {
        XCTAssertEqual(JapaneseHolidays.name(of: key("2006-04-29")), "みどりの日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2007-04-29")), "昭和の日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2006-05-04")), "国民の休日", "pre-2007 5/4 sandwich")
        XCTAssertNil(JapaneseHolidays.name(of: key("2003-05-04")), "pre-2007: a Sunday is never a 国民の休日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2003-05-05")), "こどもの日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2002-07-20")), "海の日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2018-12-23")), "天皇誕生日")
        XCTAssertNil(JapaneseHolidays.name(of: key("2019-12-23")), "no 天皇誕生日 in 2019")
        XCTAssertNil(JapaneseHolidays.name(of: key("2020-10-12")), "no October スポーツの日 in 2020")
        XCTAssertNil(JapaneseHolidays.name(of: key("2021-10-11")), "no October スポーツの日 in 2021")
        XCTAssertNil(JapaneseHolidays.name(of: key("2020-08-11")), "山の日 moved in 2020")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2032-09-21")), "国民の休日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2092-03-19")), "春分の日", "the only 3/19 春分の日")
    }

    func testUnsupportedYearsHaveNoHolidays() {
        XCTAssertNil(JapaneseHolidays.name(of: key("1999-01-01")))
        XCTAssertNil(JapaneseHolidays.name(of: key("2100-01-01")))
        XCTAssertEqual(JapaneseHolidays.name(of: key("2099-01-01")), "元日")
        XCTAssertEqual(JapaneseHolidays.name(of: key("2000-01-01")), "元日")
        XCTAssertTrue(JapaneseHolidays.holidays(ofYear: 1999).isEmpty)
        XCTAssertTrue(JapaneseHolidays.holidays(ofYear: 2100).isEmpty)
    }

    func testNameOfDateUsesTheLocalCalendarDay() {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "Asia/Tokyo")!
        let silverWeekMidday = DayKey(year: 2026, month: 9, day: 22).startOfDay(in: calendar).addingTimeInterval(12 * 3600)
        XCTAssertEqual(JapaneseHolidays.name(of: silverWeekMidday, calendar: calendar), "国民の休日")
        let lateNewYear = DayKey(year: 2026, month: 1, day: 1).startOfDay(in: calendar).addingTimeInterval(86_399)
        XCTAssertEqual(JapaneseHolidays.name(of: lateNewYear, calendar: calendar), "元日")
        let ordinary = DayKey(year: 2026, month: 10, day: 4).startOfDay(in: calendar)
        XCTAssertNil(JapaneseHolidays.name(of: ordinary, calendar: calendar))
    }

    func testRangeQueriesInclusiveBoundsAndYearBoundaries() {
        // The 2026 Silver Week: 9/21 敬老の日, 9/22 国民の休日, 9/23 秋分の日.
        XCTAssertEqual(
            JapaneseHolidays.holidays(from: key("2026-09-21"), through: key("2026-09-22")).map { "\($0.day) \($0.name)" },
            ["2026-09-21 敬老の日", "2026-09-22 国民の休日"]
        )
        XCTAssertEqual(
            JapaneseHolidays.holidays(from: key("2026-12-27"), through: key("2027-01-11")).map { "\($0.day) \($0.name)" },
            ["2027-01-01 元日", "2027-01-11 成人の日"],
            "across a year boundary, sorted"
        )
        // A 42-day month grid of 2026-05 (Monday start: 4/27–6/7).
        let grid = MonthLayout.grid(year: 2026, month: 5)
        XCTAssertEqual(
            JapaneseHolidays.holidays(from: grid.days.first!, through: grid.days.last!).map { $0.day.description },
            ["2026-04-29", "2026-05-03", "2026-05-04", "2026-05-05", "2026-05-06"]
        )
        XCTAssertEqual(JapaneseHolidays.names(for: grid.days).count, 5)
        XCTAssertEqual(JapaneseHolidays.names(for: grid.days)[key("2026-05-06")], "振替休日")
        XCTAssertTrue(JapaneseHolidays.holidays(from: key("2026-01-02"), through: key("2026-01-01")).isEmpty, "inverted range")
        let total = (2000...2099).reduce(0) { $0 + JapaneseHolidays.holidays(ofYear: $1).count }
        XCTAssertEqual(
            JapaneseHolidays.holidays(from: key("1990-01-01"), through: key("2110-01-01")).count,
            total,
            "out-of-range years are skipped, supported years are complete"
        )
    }
