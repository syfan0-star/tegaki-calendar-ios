        XCTAssertEqual(M.minGapPoints, 2)
        XCTAssertEqual(M.minTextPoints, 11)
        XCTAssertEqual(M.topPadPoints, 3)
        XCTAssertEqual(M.bottomPadPoints, 4)
        XCTAssertEqual(M.labelPoints, 10)
