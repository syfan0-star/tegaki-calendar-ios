    func testMetrics() {
        let iphone = M.metrics(kind: .week, laneCount: 1, zoom: 0.4716, pageHeight: 630)
        XCTAssertEqual(iphone.lane, 18, "floor (10.4 lu × zoom)")
        XCTAssertEqual(iphone.gap, 2, "floor")
        XCTAssertEqual(iphone.text, 11, "floor")
        XCTAssertEqual(iphone.contentHeight, 25, "3 + 18 + 4")
        XCTAssertEqual(iphone.visibleHeight, 25)
        XCTAssertFalse(iphone.scrollsInside)
        XCTAssertEqual(iphone.laneTop(0), 3)
        XCTAssertEqual(iphone.laneTop(1), 23)
        XCTAssertEqual(iphone.laneTop(2), 43)
        XCTAssertEqual(iphone, M.Metrics(lane: 18, gap: 2, text: 11, contentHeight: 25, visibleHeight: 25, scrollsInside: false))
        let one = M.metrics(kind: .week, laneCount: 1, zoom: 1, pageHeight: 800)
        XCTAssertEqual(one.lane, 22)
        XCTAssertEqual(one.gap, 3)
        XCTAssertEqual(one.text, 13)
        XCTAssertEqual(one.contentHeight, 29, "3 + 22 + 4")
        XCTAssertEqual(one.laneTop(1), 28)
        let ipad = M.metrics(kind: .week, laneCount: 3, zoom: 0.7314, pageHeight: 1000)
        XCTAssertEqual(ipad.lane, 18, "floor (16.1)")
        XCTAssertEqual(ipad.gap, 2.1942, accuracy: 1e-3)
        XCTAssertEqual(ipad.text, 11, "floor (9.5)")
        XCTAssertEqual(ipad.contentHeight, 65.39, accuracy: 1e-2, "3 + 54 + 4.39 + 4")
        XCTAssertEqual(ipad.visibleHeight, 65.39, accuracy: 1e-2)
        XCTAssertFalse(ipad.scrollsInside)
        XCTAssertEqual(ipad.laneTop(2), 3 + 2 * (18 + 3 * 0.7314), accuracy: 1e-6)
        let ten = M.metrics(kind: .week, laneCount: 10, zoom: 0.4716, pageHeight: 630)
        XCTAssertEqual(ten.contentHeight, 205, "3 + 180 + 18 + 4")
        XCTAssertEqual(ten.visibleHeight, 205)
        XCTAssertFalse(ten.scrollsInside)
        let eleven = M.metrics(kind: .week, laneCount: 11, zoom: 0.4716, pageHeight: 630)
        XCTAssertEqual(eleven.contentHeight, 225)
        XCTAssertEqual(eleven.visibleHeight, 220, "floor(0.35 × 630)")
        XCTAssertTrue(eleven.scrollsInside)
        let zero = M.metrics(kind: .week, laneCount: 0, zoom: 0.4716, pageHeight: 630)
        XCTAssertEqual(zero.contentHeight, 0)
        XCTAssertEqual(zero.visibleHeight, 0)
        XCTAssertFalse(zero.scrollsInside)
        XCTAssertEqual(zero.lane, 18, "the lane size does not depend on the count")
        XCTAssertEqual(M.metrics(kind: .week, laneCount: -2, zoom: 0.4716, pageHeight: 630), zero, "a negative count is 0")
        let day = M.metrics(kind: .day, laneCount: 1, zoom: 0.5612, pageHeight: 600)
        XCTAssertEqual(day.lane, 18)
        XCTAssertEqual(day.gap, 2, "2 lu × 0.5612 = 1.1 → floor")
        XCTAssertEqual(day.text, 11, "14 × 0.5612 = 7.9 → floor")
        XCTAssertEqual(day.contentHeight, 25)
        let dayBig = M.metrics(kind: .day, laneCount: 2, zoom: 2, pageHeight: 2000)
        XCTAssertEqual(dayBig.lane, 44)
        XCTAssertEqual(dayBig.gap, 4)
        XCTAssertEqual(dayBig.text, 28)
        XCTAssertEqual(dayBig.contentHeight, 99, "3 + 88 + 4 + 4")
        let weekBig = M.metrics(kind: .week, laneCount: 2, zoom: 2, pageHeight: 2000)
        XCTAssertEqual(weekBig.gap, 6)
        XCTAssertEqual(weekBig.text, 26)
        XCTAssertEqual(weekBig.contentHeight, 101, "3 + 88 + 6 + 4")
        for bad in [CGFloat.nan, 0, -1, .infinity] {
            XCTAssertEqual(M.metrics(kind: .week, laneCount: 1, zoom: bad, pageHeight: 800), one, "zoom \(bad) counts as 1")
        }
        for bad in [CGFloat.nan, 0, -100, .infinity] {
            let m = M.metrics(kind: .week, laneCount: 1, zoom: 1, pageHeight: bad)
            XCTAssertEqual(m.visibleHeight, 0, "pageHeight \(bad) counts as 0")
            XCTAssertEqual(m.contentHeight, 29, "pageHeight \(bad)")
            XCTAssertTrue(m.scrollsInside, "pageHeight \(bad)")
        }
        let capped = M.metrics(kind: .week, laneCount: 5, zoom: 1, pageHeight: 100)
        XCTAssertEqual(capped.contentHeight, 129, "3 + 110 + 12 + 4")
        XCTAssertEqual(capped.visibleHeight, 35, "floor(0.35 × 100)")
        XCTAssertTrue(capped.scrollsInside)
        XCTAssertEqual(M.metrics(kind: .week, laneCount: 11, zoom: 0.4716, pageHeight: 631).visibleHeight, 220, "the cap is floored")
        XCTAssertEqual(M.metrics(kind: .month, laneCount: 1, zoom: 1, pageHeight: 800), one, "any kind but .day takes the week's lu")
    }
}
