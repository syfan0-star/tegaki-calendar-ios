import XCTest
import Foundation
import CoreGraphics
import Layout

/// The fixed all-day band of the week / day pages (M4B_CONTRACT §2.1 / §2.2): the week of
/// 2026-10-05 and the day 10/7 with the screenshot-mode demo events; "today" is 10/7 at 10:00.
final class AllDayBandTests: XCTestCase {
    private typealias F = M3aFixtures
    private typealias M = AllDayBandMetrics
    private let colW = PaperSpec.weekColumnWidth
    private var demo: [LayoutEvent] { F.demo }
    private let monday = M3aFixtures.day(2026, 10, 5)

    private func weekBand(_ events: [LayoutEvent], monday: DayKey? = nil, now: Date? = nil) -> AllDayBandLayout {
        AllDayBandEngine.week(monday: monday ?? self.monday, events: events, now: now ?? F.demoNow, calendar: F.tokyo)
    }

    private func dayBand(_ events: [LayoutEvent], day: DayKey? = nil, now: Date? = nil) -> AllDayBandLayout {
        AllDayBandEngine.day(day ?? F.day(2026, 10, 7), events: events, now: now ?? F.demoNow, calendar: F.tokyo)
    }

    func testWeekBandOfTheDemo() {
        let band = weekBand(demo)
        XCTAssertEqual(band, F.weekLayout(demo).allDayBand, "the engine and the week page agree")
        XCTAssertEqual(band.kind, .week)
        XCTAssertEqual(band.days, (5...11).map { F.day(2026, 10, $0) })
        XCTAssertEqual(band.tones, [.normal, .normal, .normal, .normal, .normal, .saturday, .sundayOrHoliday])
        XCTAssertEqual(band.paperWidth, 1400)
        XCTAssertEqual(band.gutter, 64)
        XCTAssertEqual(band.columnWidth, colW)
        XCTAssertEqual(band.columnMinX.count, 7)
        for i in 0..<7 {
            XCTAssertEqual(band.columnMinX[i], 64 + CGFloat(i) * colW, accuracy: 1e-9, "columnMinX[\(i)]")
        }
        XCTAssertEqual(band.laneCount, 1)
        XCTAssertEqual(band.todayColumn, 2)
        XCTAssertEqual(band.bars.map(\.title), ["キャンプ", "締切", "家族旅行"], "by lane, then start column")
        XCTAssertEqual(band.bars.map(\.id), band.bars.map(\.eventId), "Identifiable by the event id")
        let bars = Dictionary(uniqueKeysWithValues: band.bars.map { ($0.title, $0) })
        let camp = bars["キャンプ"]
        XCTAssertEqual(camp?.lane, 0)
        XCTAssertEqual(camp?.startCol, 0)
        XCTAssertEqual(camp?.endCol, 0)
        XCTAssertEqual(camp?.continuesLeft, true, "started 10/4")
        XCTAssertEqual(camp?.continuesRight, false)
        XCTAssertEqual(camp?.minX ?? -1, 64, accuracy: 1e-9, "no inset on the open end")
        XCTAssertEqual(camp?.maxX ?? -1, 64 + colW - 3, accuracy: 1e-9)
        XCTAssertEqual(camp?.colorHex, F.demoColors[1])
        let deadline = bars["締切"]
        XCTAssertEqual(deadline?.lane, 0)
        XCTAssertEqual(deadline?.startCol, 2)
        XCTAssertEqual(deadline?.endCol, 2)
        XCTAssertEqual(deadline?.continuesLeft, false)
        XCTAssertEqual(deadline?.continuesRight, false)
        XCTAssertEqual(deadline?.minX ?? -1, 64 + 2 * colW + 3, accuracy: 1e-9)
        XCTAssertEqual(deadline?.maxX ?? -1, 64 + 3 * colW - 3, accuracy: 1e-9)
        XCTAssertEqual(deadline?.eventId, F.demoId("締切"))
        XCTAssertEqual(deadline?.colorHex, F.demoColors[2])
        let trip = bars["家族旅行"]
        XCTAssertEqual(trip?.lane, 0)
        XCTAssertEqual(trip?.startCol, 4)
        XCTAssertEqual(trip?.endCol, 6)
        XCTAssertEqual(trip?.continuesLeft, false)
        XCTAssertEqual(trip?.continuesRight, true, "ends 10/14")
        XCTAssertEqual(trip?.minX ?? -1, 64 + 4 * colW + 3, accuracy: 1e-9)
        XCTAssertEqual(trip?.maxX ?? -1, 1400, accuracy: 1e-9, "the open end reaches the paper's edge")
        XCTAssertEqual(weekBand(demo, monday: F.day(2026, 10, 7)), band, "a non-Monday is normalized")
        XCTAssertEqual(weekBand(demo, monday: F.day(2026, 10, 11)), band, "a Sunday is normalized")
    }

    func testEmptyAndTimedOnly() {
        let none = weekBand([])
        XCTAssertEqual(none.laneCount, 0)
        XCTAssertEqual(none.bars.count, 0)
        XCTAssertEqual(none.todayColumn, 2, "today is still marked")
        XCTAssertEqual(none.tones, weekBand(demo).tones)
        XCTAssertEqual(none.days, weekBand(demo).days)
        XCTAssertNotEqual(none, weekBand(demo))
        XCTAssertEqual(weekBand([F.timed("t", 7, 9, 0, 10, 0)]).laneCount, 0, "a timed event is not in the band")
        let blank = AllDayBandLayout.empty(kind: .week, days: none.days)
        XCTAssertEqual(blank.kind, .week)
        XCTAssertEqual(blank.laneCount, 0)
        XCTAssertEqual(blank.bars.count, 0)
        XCTAssertNil(blank.todayColumn)
        XCTAssertEqual(blank.tones, none.tones, "tones are computed from the days")
        XCTAssertEqual(blank.columnMinX, none.columnMinX)
        XCTAssertEqual(blank.gutter, 64)
        XCTAssertEqual(blank.paperWidth, 1400)
        XCTAssertEqual(blank.columnWidth, colW)
        XCTAssertEqual(AllDayBandLayout.empty(kind: .month, days: none.days).gutter, 64, "any kind but .day takes the week's geometry")
        let blankDay = AllDayBandLayout.empty(kind: .day, days: [F.day(2026, 10, 7)])
        XCTAssertEqual(blankDay.kind, .day)
        XCTAssertEqual(blankDay.tones, [.normal])
        XCTAssertEqual(blankDay.gutter, 72)
        XCTAssertEqual(blankDay.paperWidth, 1000)
        XCTAssertEqual(blankDay.columnMinX, [72])
        XCTAssertEqual(blankDay.columnWidth, 588)
        XCTAssertEqual(blankDay.laneCount, 0)
        XCTAssertNil(blankDay.todayColumn)
    }

    func testLanes() {
        let stacked = weekBand(demo + [F.allDay("x", 6, 9, title: "重なる")])
        XCTAssertEqual(stacked.laneCount, 2)
        XCTAssertEqual(stacked.bars.map(\.title), ["キャンプ", "重なる", "家族旅行", "締切"])
        XCTAssertEqual(stacked.bars.map(\.lane), [0, 0, 0, 1], "the longer span takes lane 0; 締切 moves to lane 1")
        XCTAssertEqual(stacked.bars[1].startCol, 1)
        XCTAssertEqual(stacked.bars[1].endCol, 3, "10/6 … 10/9 exclusive")
        XCTAssertEqual(stacked.bars[1].minX, 64 + colW + 3, accuracy: 1e-9)
        XCTAssertEqual(stacked.bars[1].maxX, 64 + 4 * colW - 3, accuracy: 1e-9)
        XCTAssertEqual(stacked.bars[3].startCol, 2)
        var pile: [LayoutEvent] = []
        for i in 0..<40 { pile.append(F.allDay("pile\(i)", 5, 6, title: "p\(i)")) }
        let piled = weekBand(pile)
        XCTAssertEqual(piled.laneCount, 40, "no thinning")
        XCTAssertEqual(piled.bars.count, 40)
        XCTAssertEqual(piled.bars.map(\.lane), Array(0..<40))
        XCTAssertEqual(Set(piled.bars.map(\.startCol)), [0])
        XCTAssertEqual(F.weekLayout(pile).size.height, 1920, "the paper does not grow with the band")
    }

    func testHolidayWeek() {
        let week = weekBand(demo, monday: F.day(2026, 10, 12))
        XCTAssertEqual(week.tones, [.sundayOrHoliday, .normal, .normal, .normal, .normal, .saturday, .sundayOrHoliday], "10/12 スポーツの日")
        XCTAssertNil(week.todayColumn)
        XCTAssertEqual(week.days.first, F.day(2026, 10, 12))
        XCTAssertEqual(week.bars.map(\.title), ["家族旅行", "ゴミの日", "健康診断", "誕生日", "資料提出締切"])
        XCTAssertEqual(week.bars.map(\.lane), [0, 0, 1, 2, 3])
        XCTAssertEqual(week.laneCount, 4)
        XCTAssertEqual(week.bars[0].startCol, 0)
        XCTAssertEqual(week.bars[0].endCol, 1, "the trip ends Tuesday 10/13")
        XCTAssertEqual(week.bars[0].continuesLeft, true)
        XCTAssertEqual(week.bars[0].continuesRight, false)
        XCTAssertEqual(week.bars[0].minX, 64, accuracy: 1e-9)
        XCTAssertEqual(week.bars[0].maxX, 64 + 2 * colW - 3, accuracy: 1e-9)
        XCTAssertEqual(Set(week.bars.dropFirst().map(\.startCol)), [4])
        XCTAssertEqual(F.weekLayout([], focus: F.day(2026, 10, 12)).allDayBand.tones, week.tones)
    }

    func testDayBand() {
        let band = dayBand(demo)
        XCTAssertEqual(band, F.dayLayout(demo).allDayBand, "the engine and the day page agree")
        XCTAssertEqual(band.kind, .day)
        XCTAssertEqual(band.days, [F.day(2026, 10, 7)])
        XCTAssertEqual(band.tones, [.normal])
        XCTAssertEqual(band.paperWidth, 1000)
        XCTAssertEqual(band.gutter, 72)
        XCTAssertEqual(band.columnMinX, [72])
        XCTAssertEqual(band.columnWidth, 588)
        XCTAssertEqual(band.laneCount, 1)
        XCTAssertEqual(band.todayColumn, 0)
        XCTAssertEqual(band.bars.count, 1)
        XCTAssertEqual(band.bars[0].title, "締切")
        XCTAssertEqual(band.bars[0].eventId, F.demoId("締切"))
        XCTAssertEqual(band.bars[0].minX, 76, "72 + 4")
        XCTAssertEqual(band.bars[0].maxX, 648, "660 − 12")
        XCTAssertEqual(band.bars[0].lane, 0)
        XCTAssertEqual(band.bars[0].startCol, 0)
        XCTAssertEqual(band.bars[0].endCol, 0)
        XCTAssertFalse(band.bars[0].continuesLeft)
        XCTAssertFalse(band.bars[0].continuesRight)
        XCTAssertEqual(band.bars[0].colorHex, F.demoColors[2])
        let sunday = dayBand(demo, day: F.day(2026, 10, 11))
        XCTAssertEqual(sunday.tones, [.sundayOrHoliday])
        XCTAssertNil(sunday.todayColumn)
        XCTAssertEqual(sunday.bars.map(\.title), ["家族旅行"])
        XCTAssertTrue(sunday.bars[0].continuesLeft)
        XCTAssertTrue(sunday.bars[0].continuesRight)
        XCTAssertEqual(dayBand([], day: F.day(2026, 10, 12)).tones, [.sundayOrHoliday], "a holiday")
        XCTAssertEqual(dayBand([], day: F.day(2026, 10, 10)).tones, [.saturday])
        XCTAssertEqual(dayBand(demo, day: F.day(2026, 10, 8)).laneCount, 0)
        let busy = dayBand(demo + [F.allDay("a", 7, 8, title: "a"), F.allDay("b", 1, 20, title: "b")])
        XCTAssertEqual(busy.laneCount, 3)
        XCTAssertEqual(busy.bars.map(\.title), ["b", "a", "締切"], "earlier start first, then title")
        XCTAssertEqual(busy.bars.map(\.lane), [0, 1, 2], "lane = display order")
        XCTAssertEqual(busy.bars.map(\.minX), [76, 76, 76])
        XCTAssertTrue(busy.bars[0].continuesLeft)
        XCTAssertTrue(busy.bars[0].continuesRight)
        XCTAssertEqual(F.dayLayout(demo + [F.allDay("a", 7, 8), F.allDay("b", 1, 20)]).size.height, 3100, "the paper does not grow with the band (1.1: 2400 + the free memo area 700)")
    }

    func testDayAtPaperX() {
        // M4c, M4C_CONTRACT §4.3: the double tap on a column of the fixed band → that day.
        let band = weekBand(demo)
        XCTAssertEqual(band.day(atPaperX: 64), monday, "the first column's left edge")
        XCTAssertEqual(band.day(atPaperX: 64 + 6.5 * colW), F.day(2026, 10, 11), "the middle of the last column")
        XCTAssertEqual(band.day(atPaperX: 1400), F.day(2026, 10, 11), "x 1400 is Sunday")
        XCTAssertNil(band.day(atPaperX: 10), "the 「終日」 gutter")
        XCTAssertNil(band.day(atPaperX: 63.9))
        XCTAssertNil(band.day(atPaperX: 1401))
        XCTAssertNil(band.day(atPaperX: -5), "a centring margin (negative lu)")
        XCTAssertNil(band.day(atPaperX: .nan))
        XCTAssertNil(band.day(atPaperX: .infinity))
        XCTAssertEqual(band.day(atPaperX: 64 + 2 * colW), F.day(2026, 10, 7), "a column boundary belongs to its own column")
        XCTAssertEqual(band.day(atPaperX: 64 + 2 * colW - 0.01), F.day(2026, 10, 6))
        for col in 0..<7 {
            XCTAssertEqual(band.day(atPaperX: band.columnMinX[col] + 5), F.day(2026, 10, 5 + col), "column \(col)")
            XCTAssertEqual(band.day(atPaperX: band.columnMinX[col] + 5), F.weekLayout(demo).dayAt(point: CGPoint(x: band.columnMinX[col] + 5, y: 100)), "the band and the paper agree on column \(col)")
        }
        XCTAssertEqual(AllDayBandLayout.empty(kind: .week, days: band.days).day(atPaperX: 700), F.day(2026, 10, 8), "an empty band has the same columns")
        XCTAssertNil(AllDayBandLayout.empty(kind: .week, days: []).day(atPaperX: 700), "a band without days")
        let single = dayBand(demo)
        XCTAssertEqual(single.day(atPaperX: 72), F.day(2026, 10, 7), "the column's left edge")
        XCTAssertEqual(single.day(atPaperX: 500), F.day(2026, 10, 7))
        XCTAssertEqual(single.day(atPaperX: 1000), F.day(2026, 10, 7), "the paper's right edge (the memo area) is still the day")
        XCTAssertNil(single.day(atPaperX: 71), "the gutter")
        XCTAssertNil(single.day(atPaperX: 71.9))
        XCTAssertNil(single.day(atPaperX: 1001))
        XCTAssertNil(single.day(atPaperX: .nan))
        XCTAssertEqual(dayBand([], day: F.day(2026, 10, 12)).day(atPaperX: 300), F.day(2026, 10, 12), "another day's band")
    }

